const dictionaries: Record<string, Dict> = {
  en,
  "zh-CN": zhCN,
  "zh-TW": zhTW,
};

export function useT() {
  const language = String(
    useAppStore((state) => state.settings.language ?? "system"),
  );
  // The site is Chinese-first: "system" and unknown values resolve to zh-CN.
  const lang = language === "system" || language === "" ? "zh-CN" : language;
  const dict = dictionaries[lang] ?? zhCN;
  return (key: string, vars?: Record<string, string | number>) => {
    let value = dict[key] ?? zhCN[key] ?? en[key] ?? key;
    if (vars) {
      for (const [name, replacement] of Object.entries(vars)) {
        value = value.replaceAll(`@${name}`, String(replacement));
      }
    }
    return value;
  };
}

export function formatDuration(seconds: number): string {
  if (!Number.isFinite(seconds) || seconds <= 0) return "0 分钟";
  const hours = Math.floor(seconds / 3600);
  const minutes = Math.floor((seconds % 3600) / 60);
  if (hours > 0) return `${hours} 小时 ${minutes} 分钟`;
  if (minutes > 0) return `${minutes} 分钟`;
  return `${Math.max(1, Math.round(seconds))} 秒`;
}

export function formatSecondsShort(seconds: number): string {
  if (seconds < 60) return `${Math.round(seconds)}秒`;
  if (seconds < 3600) return `${Math.round(seconds / 60)}分`;
  return `${(seconds / 3600).toFixed(1)}小时`;
}
